"""Render a JiraTicket as Markdown, Jira wiki markup, plain text or JSON, and write the files safely."""
from __future__ import annotations

import json
import re
from pathlib import Path

from .jira import JiraTicket
from .sanitize import md_escape, wiki_escape

FORMATS = {"markdown": ("md", "text/markdown"), "text": ("txt", "text/plain"),
           "json": ("json", "application/json"), "jira": ("jira.txt", "text/plain")}


def blocks(t: JiraTicket) -> list[tuple]:
    """Format-neutral document model: (kind, ...) tuples."""
    reviewed = bool(t.review.get("checked"))
    edited = t.extra.get("edited_fields") if t.extra else None
    b: list[tuple] = [("h1", t.title),
                      ("note", f"{t.review['status']}. Generated by Bug Report & Log Analyzer Agent v{t.tool_version} on {t.generated_at}. "
                               + ("Reviewed by a human" + (f" (edited: {', '.join(edited)})." if edited else ".")
                                  if reviewed else "A human must review it before it is filed.")),
                      ("checklist", t.review["checklist"], reviewed),
                      ("h2", "Summary"), ("p", t.summary),
                      ("kv", [("Severity", t.severity), ("Priority (recommendation)", f"{t.priority} - {t.priority_rationale}"),
                              ("Affected component", t.component), ("Labels", ", ".join(t.labels))]),
                      ("h2", "Environment"), ("kv", t.environment),
                      ("h2", "Error message"), ("code", "text", t.error_message or "(none)"),
                      ("h2", "Steps to reproduce (suggested, derived from the logged call path; not verified)"),
                      ("numbered", t.steps_to_reproduce or ["No steps could be derived from the log."]),
                      ("h2", "Expected behavior"), ("p", t.expected_behavior),
                      ("h2", "Actual behavior (observed)"), ("bullets", t.actual_behavior),
                      ("h2", "Root-cause analysis"),
                      ("h3", "Observed evidence (measured from the log and code)"),
                      ("bullets", [f"{e['text']} [{e['source']}]" for e in t.observed_evidence]),
                      ("h3", "Probable root cause (HYPOTHESIS, not confirmed)"), ("p", t.root_cause_hypothesis)]
    if t.alternatives:
        b += [("p", "Alternative possibilities:"), ("bullets", t.alternatives)]
    conf = t.confidence
    conf_text = f"Heuristic confidence: {conf['heuristic']} (a rule-based score, not a calibrated probability)."
    if conf.get("ai") is not None:
        conf_text += f" The language model's own estimate: {conf['ai']} (also unverified)."
    b += [("p", conf_text), ("bullets", conf["basis"]),
          ("h2", "Impact"), ("p", "Observed:"), ("bullets", t.impact_observed),
          ("p", f"Inferred (hypothesis): {t.impact_inferred}")]
    b.append(("h2", "Relevant source code"))
    if not t.code:
        b.append(("p", "No source code was located for this incident. The exact source location is not verified."))
    for c in t.code:
        tag = "VERIFIED against the stack trace" if c["verified"] else "NOT verified"
        b += [("p", f"{c['file']} lines {c['lines']}" + (f" in {c['function']}()" if c["function"] else "") + f" - {tag}. {c['note']}"),
              ("code", c["language"], c["snippet"])]
    b += [("h2", "Suggested fix (hypotheses to evaluate)"), ("bullets", t.suggested_fix or ["None proposed."]),
          ("h2", "Recommended investigation"), ("bullets", t.investigation or ["None proposed."]),
          ("h2", "Testing recommendation"), ("bullets", t.testing),
          ("h2", "Logs")]
    if t.logs.get("context_before"):
        b += [("p", "Events before the first occurrence:"), ("code", "text", "\n".join(t.logs["context_before"]))]
    b += [("p", f"Stack trace of a sample event (log lines {t.logs['first_line']}-{t.logs['last_line']} cover this group):"),
          ("code", "text", t.logs.get("stack_trace") or "(no stack trace)")]
    if t.logs.get("context_after"):
        b += [("p", "Events after the first occurrence:"), ("code", "text", "\n".join(t.logs["context_after"]))]
    if t.ai.get("enhanced"):
        b.append(("h2", "AI-assisted analysis"))
        b.append(("p", f"Inference sections were refined by {t.ai['provider']}. Rule-based baseline hypothesis: {t.ai['baseline_hypothesis']}"))
        if t.ai["supporting_evidence"]:
            b += [("p", "Evidence the model cited:"), ("bullets", [f"{e['id']}: {e['text']}" for e in t.ai["supporting_evidence"]])]
        if t.ai["caveats"]:
            b += [("p", "Caveats from the model:"), ("bullets", t.ai["caveats"])]
        if t.ai["warnings"]:
            b += [("p", "Automatic warnings:"), ("bullets", t.ai["warnings"])]
    elif t.ai.get("fallback_reason"):
        b.append(("p", f"AI refinement was not used: {t.ai['fallback_reason']}"))
    if t.redactions:
        b.append(("p", "Redaction: " + ", ".join(f"{k} x{v}" for k, v in sorted(t.redactions.items())) + " masked in this report."))
    b.append(("note", t.disclaimer))
    return b


# ----------------------------------------------------------------------------- Markdown
def _fence(text: str) -> str:
    longest = max((len(m) for m in re.findall(r"`+", text)), default=0)
    return "`" * max(3, longest + 1)


def render_markdown(t: JiraTicket) -> str:
    e = md_escape
    out: list[str] = []
    for blk in blocks(t):
        kind = blk[0]
        if kind in ("h1", "h2", "h3"):
            out.append(f"{'#' * int(kind[1])} {e(blk[1])}\n")
        elif kind == "p":
            out.append(e(blk[1]) + "\n")
        elif kind == "note":
            out.append("> " + e(blk[1]).replace("\n", "\n> ") + "\n")
        elif kind == "bullets":
            out.append("\n".join(f"- {e(i)}" for i in blk[1]) + "\n")
        elif kind == "checklist":
            out.append("\n".join(f"- [{'x' if blk[2] else ' '}] {e(i)}" for i in blk[1]) + "\n")
        elif kind == "numbered":
            out.append("\n".join(f"{n}. {e(i)}" for n, i in enumerate(blk[1], 1)) + "\n")
        elif kind == "kv":
            esc = lambda s: e(str(s)).replace("|", "\\|").replace("\n", " ")  # noqa: E731
            out.append("| Field | Value |\n|---|---|\n" + "\n".join(f"| {esc(k)} | {esc(v)} |" for k, v in blk[1]) + "\n")
        elif kind == "code":
            f = _fence(blk[2])
            out.append(f"{f}{blk[1]}\n{blk[2]}\n{f}\n")
    return "\n".join(out)


# ----------------------------------------------------------------------------- Jira wiki markup
def _wiki_escape(text: str) -> str:
    return wiki_escape(text)


def render_wiki(t: JiraTicket) -> str:
    out: list[str] = []
    for blk in blocks(t):
        kind = blk[0]
        if kind in ("h1", "h2", "h3"):
            out.append(f"h{kind[1]}. {_wiki_escape(blk[1])}\n")
        elif kind == "p":
            out.append(_wiki_escape(blk[1]) + "\n")
        elif kind == "note":
            out.append("{quote}\n" + _wiki_escape(blk[1]) + "\n{quote}\n")
        elif kind == "bullets":
            out.append("\n".join(f"* {_wiki_escape(i)}" for i in blk[1]) + "\n")
        elif kind == "checklist":
            out.append("\n".join(f"* {'(/)' if blk[2] else '(x)'} {_wiki_escape(i)}" for i in blk[1]) + "\n")
        elif kind == "numbered":
            out.append("\n".join(f"# {_wiki_escape(i)}" for i in blk[1]) + "\n")
        elif kind == "kv":
            out.append("\n".join(f"||{_wiki_escape(k)}|{_wiki_escape(str(v))}|" for k, v in blk[1]) + "\n")
        elif kind == "code":
            lang = blk[1] if blk[1] in ("python", "java", "javascript", "text") else "none"
            safe = blk[2].replace("{code", "{ code")
            out.append(f"{{code:{lang}}}\n{safe}\n{{code}}\n")
    return "\n".join(out)


# ----------------------------------------------------------------------------- plain text / JSON
def render_text(t: JiraTicket) -> str:
    out: list[str] = []
    for blk in blocks(t):
        kind = blk[0]
        if kind == "h1":
            out.append(blk[1].upper() + "\n" + "=" * min(len(blk[1]), 78) + "\n")
        elif kind in ("h2", "h3"):
            out.append(("\n" if kind == "h2" else "") + blk[1] + "\n" + ("-" if kind == "h2" else "~") * min(len(blk[1]), 78) + "\n")
        elif kind in ("p", "note"):
            out.append(blk[1] + "\n")
        elif kind == "bullets":
            out.append("\n".join(f"  * {i}" for i in blk[1]) + "\n")
        elif kind == "checklist":
            out.append("\n".join(f"  [{'x' if blk[2] else ' '}] {i}" for i in blk[1]) + "\n")
        elif kind == "numbered":
            out.append("\n".join(f"  {n}. {i}" for n, i in enumerate(blk[1], 1)) + "\n")
        elif kind == "kv":
            out.append("\n".join(f"  {k}: {v}" for k, v in blk[1]) + "\n")
        elif kind == "code":
            out.append("\n".join("    " + line for line in blk[2].split("\n")) + "\n")
    return "\n".join(out)


def render_json(t: JiraTicket) -> str:
    return json.dumps(t.to_dict(), indent=2, ensure_ascii=False)


RENDERERS = {"markdown": render_markdown, "text": render_text, "json": render_json, "jira": render_wiki}


def safe_basename(name: str) -> str:
    base = re.sub(r"[^A-Za-z0-9._-]+", "-", Path(str(name).replace("\\", "/")).name).strip(".-")
    return (base or "bug-report")[:80]


def export_bytes(t: JiraTicket, fmt: str) -> tuple[str, str, bytes]:
    """(file name, mime type, content) for a download button."""
    if fmt not in FORMATS:
        raise ValueError(f"Unknown format '{fmt}'. Use: {', '.join(FORMATS)}")
    ext, mime = FORMATS[fmt]
    return f"bug-report-{safe_basename(t.group_id)}.{ext}", mime, RENDERERS[fmt](t).encode("utf-8")


def write_exports(t: JiraTicket, out_dir, formats=("markdown", "text", "json", "jira")) -> list[Path]:
    """Write the chosen formats into `out_dir` (created if needed); file names are sanitized."""
    directory = Path(out_dir)
    directory.mkdir(parents=True, exist_ok=True)
    paths = []
    for fmt in formats:
        name, _, data = export_bytes(t, fmt)
        p = directory / name
        p.write_bytes(data)
        paths.append(p)
    return paths
