"""Safe repository scanner. Reads source files only; never imports, runs or follows links out of the tree."""
from __future__ import annotations

import fnmatch
import os
import time
from pathlib import Path

from config import DEFAULT_EXCLUDED_DIRS
from security.policy import is_inside

from .models import RepoScan, ScanStats, SourceFile

LANGUAGES = {
    ".py": "python", ".js": "javascript", ".jsx": "javascript", ".mjs": "javascript", ".cjs": "javascript",
    ".ts": "typescript", ".tsx": "typescript", ".java": "java",
}
MAX_FILE_BYTES = 512 * 1024
MAX_FILES = 20_000
MAX_LINE_LEN = 2000
_GENERATED_MARKERS = ("@generated", "do not edit", "code generated by", "auto-generated", "autogenerated")


class ScanError(ValueError):
    """The repository path is missing or not a directory."""


def _excluded(name: str, patterns) -> bool:
    return any(fnmatch.fnmatch(name, p) for p in patterns)


def read_git_info(root: Path) -> dict | None:
    """Branch and commit read straight from .git files (no subprocess, no credentials)."""
    git = root / ".git"
    try:
        if not git.is_dir():
            return None
        head = (git / "HEAD").read_text(encoding="utf-8").strip()
        if head.startswith("ref:"):
            ref = head.split(":", 1)[1].strip()
            commit = None
            ref_file = git / ref
            if ref_file.is_file():
                commit = ref_file.read_text(encoding="utf-8").strip()
            elif (git / "packed-refs").is_file():
                for line in (git / "packed-refs").read_text(encoding="utf-8").splitlines():
                    if line.endswith(" " + ref):
                        commit = line.split()[0]
            return {"branch": ref.removeprefix("refs/heads/"), "commit": commit}
        return {"branch": None, "commit": head}
    except OSError:
        return None


def scan_repository(root, *, excluded_dirs=DEFAULT_EXCLUDED_DIRS, max_file_bytes: int = MAX_FILE_BYTES,
                    max_files: int = MAX_FILES) -> RepoScan:
    root_path = Path(root)
    if not root_path.exists() or not root_path.is_dir():
        raise ScanError(f"Not a directory: {root_path}")
    root_r = root_path.resolve()
    stats = ScanStats()
    files: dict[str, SourceFile] = {}
    t0 = time.perf_counter()

    for dirpath, dirnames, filenames in os.walk(root_r, followlinks=False):
        keep = []
        for d in sorted(dirnames):
            full = Path(dirpath, d)
            if _excluded(d, excluded_dirs):
                stats.directories_excluded += 1
            elif full.is_symlink():
                stats.skipped["symlink"] += 1
            elif not is_inside(Path(os.path.realpath(full)), root_r):   # junctions and other reparse points
                stats.skipped["outside_root"] += 1
            else:
                keep.append(d)
        dirnames[:] = keep
        for fname in sorted(filenames):
            lang = LANGUAGES.get(Path(fname).suffix.lower())
            if lang is None:
                stats.skipped["unsupported_extension"] += 1
                continue
            path = Path(dirpath, fname)
            if path.is_symlink():
                stats.skipped["symlink"] += 1
                continue
            if not is_inside(Path(os.path.realpath(path)), root_r):
                stats.skipped["outside_root"] += 1
                continue
            if len(files) >= max_files:
                stats.skipped["max_files_reached"] += 1
                continue
            try:
                if path.stat().st_size > max_file_bytes:
                    stats.skipped["too_large"] += 1
                    continue
                data = path.read_bytes()
            except OSError:
                stats.skipped["unreadable"] += 1
                continue
            if b"\x00" in data[:8000]:
                stats.skipped["binary"] += 1
                continue
            lines = data.decode("utf-8-sig", errors="replace").splitlines()
            if lines and max(len(l) for l in lines) > MAX_LINE_LEN:
                stats.skipped["minified_or_generated"] += 1
                continue
            if any(m in "\n".join(lines[:5]).lower() for m in _GENERATED_MARKERS):
                stats.skipped["generated"] += 1
                continue
            rel = path.relative_to(root_r).as_posix()
            files[rel] = SourceFile(rel, path, lang, lines)
            stats.files_scanned += 1
            stats.total_lines += len(lines)
            stats.by_language[lang] += 1

    stats.duration_seconds = time.perf_counter() - t0
    return RepoScan(root=root_r, files=files, stats=stats, git=read_git_info(root_r))
