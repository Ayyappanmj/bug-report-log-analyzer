"""Deterministic root-cause analysis.

For each error group it assembles (1) OBSERVED evidence measured from the log and code, and (2) an INFERENCE section
(hypothesis, alternatives, fixes) taken from the rule library. Observed statements never contain hedging language;
inference statements are always hypotheses. Confidence is a documented heuristic score, not a calibrated probability.
"""
from __future__ import annotations

from dataclasses import dataclass, field
from datetime import datetime

from code_analyzer.models import CodeContext, RetrievalResult
from log_analyzer.grouper import ErrorGroup

from .rules import RULES, Rule, match_rule

DISCLAIMER = ("Generated by deterministic rules from the uploaded log and code. 'Observed evidence' was measured; "
              "everything under inference is a hypothesis to verify, not a confirmed fact.")
DISCLAIMER_AI = ("The inference sections were written by a language model from the measured evidence and checked only for format, "
                "not for truth. Treat them as hypotheses to verify. Observed evidence is measured and never model-written.")
MAX_TRACE_LINES = 60
MAX_CONFIDENCE = 0.85


@dataclass
class EvidenceItem:
    text: str
    source: str


@dataclass
class RootCauseReport:
    group_id: str
    incident: str
    severity: str
    category: str
    rule_id: str | None
    first_occurrence: str | None
    last_occurrence: str | None
    frequency: int
    affected_services: list[str]
    exception: str | None
    error_message: str
    stack_trace: str
    pattern: dict
    observed_evidence: list[EvidenceItem]
    probable_root_cause: str
    alternative_possibilities: list[str]
    observed_impact: list[str]
    inferred_impact: str
    affected_files: list[str]
    code_context: list[dict]
    code_location_verified: bool
    code_strategy: str
    recommended_investigation: list[str]
    recommended_fix: list[str]
    reproduction_steps: list[str]
    related_group_ids: list[str]
    confidence: float
    confidence_basis: list[str]
    generated_by: str = "deterministic-rules"
    disclaimer: str = DISCLAIMER
    notes: list[str] = field(default_factory=list)
    # set only by ai.enhancer when an optional LLM refined the inference sections
    baseline_probable_root_cause: str | None = None
    ai_enhanced: bool = False
    ai_provider: str | None = None
    ai_confidence: float | None = None
    ai_supporting_evidence: list[dict] = field(default_factory=list)
    ai_caveats: list[str] = field(default_factory=list)
    ai_warnings: list[str] = field(default_factory=list)
    ai_attempts: int = 0
    ai_fallback_reason: str | None = None

    def to_dict(self) -> dict:
        d = dict(self.__dict__)
        d["observed_evidence"] = [{"text": e.text, "source": e.source} for e in self.observed_evidence]
        return d


def _fmt(dt: datetime | None) -> str | None:
    return dt.strftime("%Y-%m-%d %H:%M:%S") if dt else None


def analyze_pattern(group: ErrorGroup, log_span: tuple[datetime, datetime] | None = None) -> dict:
    """Timing pattern of a group, computed from its per-minute counts."""
    tl = group.timeline
    if not tl:
        return {"label": "no timestamps" if group.count else "none", "active_minutes": 0, "span_minutes": 0,
                "peak_minute": None, "peak_count": 0, "share_of_log_span": None}
    keys = sorted(tl)
    p = lambda k: datetime.strptime(k, "%Y-%m-%d %H:%M")  # noqa: E731
    span = int((p(keys[-1]) - p(keys[0])).total_seconds() // 60) + 1
    active = len(keys)
    density = active / span
    peak_minute, peak_count = max(tl.items(), key=lambda kv: (kv[1], kv[0]))
    if group.count == 1:
        label = "single occurrence"
    elif density >= 0.8 and group.count >= 10:
        label = "sustained burst"
    elif density < 0.5:
        label = "sporadic"
    else:
        label = "intermittent"
    share = None
    if log_span and log_span[1] > log_span[0]:
        total_min = (log_span[1] - log_span[0]).total_seconds() / 60 + 1
        share = round(min(span / total_min, 1.0), 3)
    return {"label": label, "active_minutes": active, "span_minutes": span, "peak_minute": peak_minute,
            "peak_count": peak_count, "share_of_log_span": share}


class RootCauseAnalyzer:
    def __init__(self, rules: tuple[Rule, ...] = RULES):
        self.rules = rules

    # ------------------------------------------------------------------ evidence builders
    @staticmethod
    def _code_evidence(retrieval: RetrievalResult | None) -> list[EvidenceItem]:
        items: list[EvidenceItem] = []
        for ctx in (retrieval.contexts if retrieval else [])[:2]:
            if ctx.file_path is None or ctx.target_line is None:
                continue
            line_text = next((t.strip() for n, t in ctx.snippet if n == ctx.target_line), "")
            where = f"{ctx.file_path}:{ctx.target_line}" + (f" in {ctx.qualname}()" if ctx.qualname else "")
            items.append(EvidenceItem(f"Source location {where} reads `{line_text}`. {ctx.note}", where))
        return items

    def analyze(self, group: ErrorGroup, retrieval: RetrievalResult | None = None,
                all_groups: list[ErrorGroup] | None = None,
                log_span: tuple[datetime, datetime] | None = None) -> RootCauseReport:
        all_groups = all_groups or []
        by_id = {g.id: g for g in all_groups}
        sample = group.samples[0] if group.samples else None
        rule = match_rule(f"{group.exception_type or ''} {group.normalized_message} {group.title}", self.rules)
        pattern = analyze_pattern(group, log_span)
        src = f"log lines {group.first_line}-{group.last_line}"
        ev: list[EvidenceItem] = []
        basis: list[str] = []

        ev.append(EvidenceItem(
            f"{group.count} event(s) in this group; first seen {_fmt(group.first_seen) or 'at an unknown time'}, "
            f"last seen {_fmt(group.last_seen) or 'at an unknown time'}.", src))
        if pattern["peak_minute"]:
            ev.append(EvidenceItem(
                f"Timing pattern: {pattern['label']}; events in {pattern['active_minutes']} of {pattern['span_minutes']} "
                f"minute(s) between first and last occurrence; peak {pattern['peak_count']} in minute {pattern['peak_minute']}.", src))
        if group.services:
            ev.append(EvidenceItem("Logged by: " + ", ".join(f"{s} ({n})" for s, n in group.services.most_common(5)) + ".", src))
        if group.exception_type:
            extra = f"; surfaced to callers as {group.surfaced_type}" if group.surfaced_type and group.surfaced_type != group.exception_type else ""
            ev.append(EvidenceItem(f"Exception type recorded: {group.exception_type}{extra}.", src))
        if sample and sample.message:
            ev.append(EvidenceItem(f"Sample message: {sample.message[:240]}", f"log line {sample.line_no}"))
        if group.frames:
            path = " -> ".join(f.function for f in reversed(group.frames))
            ev.append(EvidenceItem(f"Call path in the stack trace (outermost to raise site): {path}.", f"log line {sample.line_no}" if sample else src))
        if group.request_ids:
            ev.append(EvidenceItem(f"{len(group.request_ids)} distinct request ID(s) are attached to this group.", src))

        related = [by_id[r] for r in group.related if r in by_id]
        for rg in related[:3]:
            shared = len(group.request_ids & rg.request_ids)
            ev.append(EvidenceItem(f"Shares {shared} request ID(s) with {rg.id} ({rg.title[:70]}, {rg.count} events).", f"{group.id}/{rg.id}"))

        prec_found = False
        if rule.precursors and group.first_seen:
            for og in all_groups:
                if (og.id != group.id and og.severity == "MEDIUM" and og.first_seen and og.first_seen < group.first_seen
                        and rule.precursors.search(og.title)):
                    mins = (group.first_seen - og.first_seen).total_seconds() / 60
                    ev.append(EvidenceItem(f"{og.count} '{og.title[:60]}' event(s) ({og.id}) began {_fmt(og.first_seen)}, "
                                           f"{mins:.1f} minute(s) before the first event of this group.", og.id))
                    prec_found = True
                    if sum("began" in e.text for e in ev) >= 3:
                        break
        overlap = 0
        if group.first_seen:
            for og in all_groups:
                if (og.id != group.id and og.count >= 5 and og.severity in ("CRITICAL", "HIGH") and og.first_seen
                        and og.last_seen and og.first_seen <= group.first_seen <= og.last_seen and og.id not in group.related):
                    ev.append(EvidenceItem(f"First event occurred during the active window of {og.id} ({og.title[:60]}; "
                                           f"{_fmt(og.first_seen)} to {_fmt(og.last_seen)}).", og.id))
                    overlap += 1
                    if overlap >= 2:
                        break
        code_ev = self._code_evidence(retrieval)
        ev.extend(code_ev)

        verified = bool(retrieval and retrieval.verified_contexts)
        has_code = bool(retrieval and retrieval.contexts)
        if retrieval and not has_code:
            ev.append(EvidenceItem("No source code could be located for this group in the provided repository.", "code search"))

        # ---- impact (observed vs inferred)
        impact_obs: list[str] = []
        statuses = dict(group.http_statuses)
        for rg in related:
            for k, v in rg.http_statuses.items():
                statuses[k] = statuses.get(k, 0) + v
        if group.request_ids:
            impact_obs.append(f"{len(group.request_ids)} distinct request ID(s) carry this error.")
        server_errors = {k: v for k, v in statuses.items() if k >= 500}
        if server_errors:
            impact_obs.append("HTTP responses recorded for this group or its linked groups: " +
                              ", ".join(f"{k} x{v}" for k, v in sorted(server_errors.items())) + ".")
        affected = sorted({s for g in [group, *related] for s in g.services})
        if affected:
            impact_obs.append("Services that logged this or linked problems: " + ", ".join(affected) + ".")
        if not group.request_ids and not statuses:
            impact_obs.insert(0, "No request IDs or HTTP statuses were attached to this group, so user impact cannot be measured from the log.")

        # ---- inference
        hypothesis = rule.hypothesis
        if rule.symptom and related:
            top = max(related, key=lambda g: g.score)
            hypothesis += f" The shared request IDs point to {top.id} ({top.title[:70]}) as the more likely origin."
        elif rule.symptom and overlap:
            hypothesis += " Its timing overlaps another active error group, which may be the origin."

        # ---- confidence (heuristic)
        conf = rule.base_confidence
        basis.append(f"{conf:+.2f} base for pattern '{rule.id}'" if rule.id != "generic" else f"{conf:+.2f} base (no known pattern matched)")
        if verified:
            conf += 0.10
            basis.append("+0.10 source location verified against the stack trace")
        elif has_code:
            basis.append("+0.00 source code found but its location is not verified")
        else:
            conf -= 0.10
            basis.append("-0.10 no source code located")
        if group.has_stack_trace:
            conf += 0.05
            basis.append("+0.05 stack trace available")
        if prec_found:
            conf += 0.10
            basis.append("+0.10 earlier warning events match the hypothesis")
        if related:
            conf += 0.05
            basis.append("+0.05 linked to another group through shared request IDs")
        if conf > MAX_CONFIDENCE:
            basis.append(f"capped at {MAX_CONFIDENCE}: rules cannot confirm a cause without runtime evidence")
        conf = round(max(0.1, min(conf, MAX_CONFIDENCE)), 2)

        files = []
        for c in (retrieval.contexts if retrieval else []):
            if c.file_path and c.file_path not in files:
                files.append(c.file_path)
        steps = list(rule.reproduction)
        if group.frames:
            steps.insert(0, "Call path to exercise: " + " -> ".join(f.function for f in reversed(group.frames)) + ".")
        if sample and sample.message:
            steps.insert(0, f"Use the sample failure as reference: \"{sample.message[:160]}\".")

        trace_lines = (sample.stack_trace.split("\n") if sample else [])[:MAX_TRACE_LINES]
        return RootCauseReport(
            group_id=group.id, incident=group.title, severity=group.severity, category=rule.category,
            rule_id=None if rule.id == "generic" else rule.id,
            first_occurrence=_fmt(group.first_seen), last_occurrence=_fmt(group.last_seen), frequency=group.count,
            affected_services=[s for s, _ in group.services.most_common()], exception=group.exception_type,
            error_message=sample.message if sample else group.normalized_message, stack_trace="\n".join(trace_lines),
            pattern=pattern, observed_evidence=ev, probable_root_cause=hypothesis,
            alternative_possibilities=list(rule.alternatives), observed_impact=impact_obs,
            inferred_impact=rule.impact_hint, affected_files=files,
            code_context=[c.to_dict() for c in (retrieval.contexts if retrieval else [])],
            code_location_verified=verified, code_strategy=retrieval.strategy if retrieval else "none",
            recommended_investigation=list(rule.investigation), recommended_fix=list(rule.fixes),
            reproduction_steps=steps, related_group_ids=list(group.related), confidence=conf, confidence_basis=basis,
            notes=list(retrieval.notes) if retrieval else [],
        )
