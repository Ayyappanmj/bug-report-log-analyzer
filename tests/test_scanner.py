import os

from pytest import raises

from code_analyzer.scanner import ScanError, read_git_info, scan_repository
from tests.helpers import write_repo


def test_scans_supported_languages_and_excludes_directories(tmp_path):
    write_repo(tmp_path, {
        "src/a.py": "x = 1\n", "web/app.js": "let a = 1;\n", "web/app.ts": "let a: number = 1;\n",
        "java/Main.java": "class Main {}\n", "README.md": "# hi\n",
        "node_modules/lib/x.js": "x", ".git/config": "[core]", "__pycache__/a.py": "x",
        ".venv/lib/y.py": "y", "build/z.py": "z", "dist/w.py": "w",
    })
    scan = scan_repository(tmp_path)
    assert sorted(scan.files) == ["java/Main.java", "src/a.py", "web/app.js", "web/app.ts"]
    assert scan.stats.files_scanned == 4 and scan.stats.directories_excluded >= 6
    assert scan.stats.skipped["unsupported_extension"] >= 1
    assert scan.stats.by_language == {"python": 1, "javascript": 1, "typescript": 1, "java": 1}


def test_custom_excluded_dirs(tmp_path):
    write_repo(tmp_path, {"keep/a.py": "x=1\n", "legacy/b.py": "y=2\n"})
    scan = scan_repository(tmp_path, excluded_dirs=("legacy",))
    assert list(scan.files) == ["keep/a.py"]


def test_binary_large_and_minified_files_are_skipped(tmp_path):
    write_repo(tmp_path, {"ok.py": "a = 1\n"})
    (tmp_path / "bin.py").write_bytes(b"abc\x00def\n")
    (tmp_path / "big.py").write_text("x = 1\n" * 200_000)
    (tmp_path / "min.js").write_text("var a=" + "1+" * 3000 + "1;\n")
    (tmp_path / "gen.py").write_text("# @generated by tool\nx = 1\n")
    scan = scan_repository(tmp_path)
    assert list(scan.files) == ["ok.py"]
    assert scan.stats.skipped["binary"] == 1 and scan.stats.skipped["too_large"] == 1
    assert scan.stats.skipped["minified_or_generated"] == 1 and scan.stats.skipped["generated"] == 1


def test_symlinks_are_not_followed(tmp_path):
    outside = tmp_path / "outside"
    repo = tmp_path / "repo"
    write_repo(outside, {"secret.py": "TOKEN = 'x'\n"})
    write_repo(repo, {"a.py": "x = 1\n"})
    try:
        os.symlink(outside, repo / "linked_dir", target_is_directory=True)
        os.symlink(outside / "secret.py", repo / "linked.py")
    except (OSError, NotImplementedError):
        return  # symlinks unavailable (e.g. Windows without privileges)
    scan = scan_repository(repo)
    assert list(scan.files) == ["a.py"] and scan.stats.skipped["symlink"] == 2


def test_missing_or_file_root_raises(tmp_path):
    with raises(ScanError):
        scan_repository(tmp_path / "nope")
    f = tmp_path / "f.py"
    f.write_text("x")
    with raises(ScanError):
        scan_repository(f)


def test_max_files_limit(tmp_path):
    write_repo(tmp_path, {f"m{i}.py": "x = 1\n" for i in range(5)})
    scan = scan_repository(tmp_path, max_files=3)
    assert scan.stats.files_scanned == 3 and scan.stats.skipped["max_files_reached"] == 2


def test_invalid_utf8_is_tolerated(tmp_path):
    (tmp_path / "a.py").write_bytes(b"x = 'caf\xe9'\n")
    assert scan_repository(tmp_path).stats.files_scanned == 1


def test_empty_repo(tmp_path):
    scan = scan_repository(tmp_path)
    assert scan.files == {} and scan.stats.files_scanned == 0 and scan.git is None


def test_git_info_read_without_running_git(tmp_path):
    (tmp_path / ".git" / "refs" / "heads").mkdir(parents=True)
    (tmp_path / ".git" / "HEAD").write_text("ref: refs/heads/main\n")
    (tmp_path / ".git" / "refs" / "heads" / "main").write_text("abc123def456\n")
    assert read_git_info(tmp_path) == {"branch": "main", "commit": "abc123def456"}
    assert scan_repository(tmp_path).git["branch"] == "main"


def test_git_info_packed_refs_and_detached(tmp_path):
    (tmp_path / ".git").mkdir()
    (tmp_path / ".git" / "HEAD").write_text("ref: refs/heads/dev\n")
    (tmp_path / ".git" / "packed-refs").write_text("# pack\nfeed1234 refs/heads/dev\n")
    assert read_git_info(tmp_path)["commit"] == "feed1234"
    (tmp_path / ".git" / "HEAD").write_text("0123456789abcdef\n")
    assert read_git_info(tmp_path) == {"branch": None, "commit": "0123456789abcdef"}
